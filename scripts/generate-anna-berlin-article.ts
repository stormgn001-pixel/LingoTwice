async function main() {
  console.log('🚀 Fast generating Anna Moves to Berlin translations...');
  const translationsMap: Record<string, string[]> = {};
  translationsMap['ru'] = ruParagraphs;

  for (const lang of LANGUAGES) {
    if (lang.code === 'ru') continue;
    console.log(`Translating into ${lang.name} (${lang.code})...`);
    const translatedList: string[] = [];
    
    for (const p of ruParagraphs) {
      try {
        const promise = translate(p, { to: lang.code });
        const timeoutPromise = new Promise((_, rej) => setTimeout(() => rej(new Error('timeout')), 3000));
        const res = await Promise.race([promise, timeoutPromise]) as string;
        translatedList.push(res || p);
      } catch (err) {
        // Fallback to English translation if available, or Russian
        const fallback = translationsMap['en']?.[ruParagraphs.indexOf(p)] || p;
        translatedList.push(fallback);
      }
    }
    translationsMap[lang.code] = translatedList;
    console.log(`  ✓ Completed ${lang.name}`);
  }

  const titleTranslations: Record<string, string> = {};
  for (const lang of LANGUAGES) {
    titleTranslations[lang.code] = lang.title;
  }

  const passages = ruParagraphs.map((ruText, idx) => {
    const pId = `anna_berlin_p${idx + 1}`;
    const pTrans: Record<string, string> = {};
    for (const lang of LANGUAGES) {
      pTrans[lang.code] = translationsMap[lang.code]?.[idx] || ruText;
    }
    return {
      id: pId,
      order: idx,
      sourceText: ruText,
      translations: pTrans
    };
  });

  const fileContent = `import { ReadingDocument } from '../types';

export const ANNA_BERLIN_ARTICLE: ReadingDocument = {
  id: 'anna_berlin_a2_001',
  title: 'Анна переезжает в Берлин (Уровень A2)',
  author: 'LingoTwice Stories',
  sourceLang: 'ru',
  targetLang: 'en',
  category: 'dialogue',
  level: 'A2',
  createdAt: 1715040000000,
  lastReadAt: Date.now(),
  readingProgress: 0,
  wordCount: 1150,
  isSample: true,
  coverImage: '/assets/images/anna_berlin_a2_1794475870811.jpg',
  titleTranslations: ${JSON.stringify(titleTranslations, null, 2)},
  passages: ${JSON.stringify(passages, null, 2)}
};
`;

  fs.writeFileSync(path.join(process.cwd(), 'src/constants/annaBerlinArticle.ts'), fileContent, 'utf-8');
  console.log('✅ Successfully generated src/constants/annaBerlinArticle.ts!');
}

main().catch(console.error);
